import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.argv[2] || 'http://127.0.0.1:13336';
const output = path.resolve('../build/workbench-tasks');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL || 'msedge' });
try {
  const context = await browser.newContext({ viewport: { width: 1366, height: 950 } });
  const commands = [], sockets = [], errors = [];
  const snapshot = { label: '非标优选任务', mode: 'nsb', phase: '扫描中', message: '正在扫描', running: true, startedAt: '2026-11-01T12:00:00Z', current: 25, total: 100, resultCount: 5, scanSuccess: 5, scanFailed: 20, params: { fileName: 'test.csv' } };
  const emit = (ws, type, data) => ws.send(JSON.stringify({ type, data }));
  await context.routeWebSocket('**/ws', ws => {
    sockets.push(ws);
    ws.onMessage(raw => {
      const message = JSON.parse(raw); commands.push(message);
      if (message.type === 'get_background_task_status') emit(ws, 'background_task_update', snapshot);
      if (message.type === 'follow_background_task') emit(ws, 'background_task_following', snapshot);
      if (message.type === 'stop_task') emit(ws, 'log', '停止信号已收到');
      if (message.type === 'run_in_background') emit(ws, 'background_task_enabled', snapshot);
    });
    emit(ws, 'init_config', { version: 'mock-test', speedTestDefault: 'auto', proxyWarning: true });
    emit(ws, 'background_task_found', snapshot);
  });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/workbench');
  await page.locator('[data-connection]').filter({ hasText: '已连接' }).waitFor();
  assert.match(await page.locator('[data-task-phase]').innerText(), /扫描中/);
  assert.equal(await page.locator('[data-task-action="background"]').isEnabled(), false);
  assert.equal(commands.some(command => command.type === 'follow_background_task'), false);
  await page.waitForFunction(() => document.querySelector('[data-task-source]').textContent.includes('test.csv'));
  await page.waitForTimeout(1200);
  assert(commands.filter(command => command.type === 'get_background_task_status').length >= 2);
  await page.locator('[data-section="tasks"]').click();
  await page.locator('[data-task-action="follow"]').click();
  await page.waitForFunction(() => document.querySelector('[data-task-action="follow"]').disabled);
  const polled = commands.filter(command => command.type === 'get_background_task_status').length;
  await page.waitForTimeout(1200);
  assert.equal(commands.filter(command => command.type === 'get_background_task_status').length, polled);
  emit(sockets.at(-1), 'log', '<img src=x onerror=alert(1)>');
  await page.locator('[data-task-log]').filter({ hasText: '<img src=x' }).waitFor();
  assert.equal(await page.locator('[data-task-log] img').count(), 0);
  emit(sockets.at(-1), 'log', '下载 https://reader:secret@example.test/input.csv?token=hidden');
  await page.waitForFunction(() => document.querySelector('[data-task-log]').textContent.includes('example.test/input.csv'));
  assert.doesNotMatch(await page.locator('[data-task-log]').innerText(), /reader:secret|token=hidden/);

  await page.locator('[data-task-action="stop"]').click();
  snapshot.startedAt = '2026-11-01T13:00:00Z';
  emit(sockets.at(-1), 'background_task_update', snapshot);
  await page.waitForFunction(() => !document.querySelector('[data-task-confirm]').open);
  assert.equal(commands.some(command => command.type === 'stop_task'), false);

  await page.locator('[data-task-action="stop"]').click();
  await page.locator('[data-task-confirm-cancel]').click();
  assert.equal(commands.some(command => command.type === 'stop_task'), false);
  await page.locator('[data-task-action="stop"]').click();
  await page.locator('[data-task-confirm-ok]').click();
  assert.equal(commands.filter(command => command.type === 'stop_task').length, 1);
  assert.match(await page.locator('[data-task-phase]').innerText(), /正在停止/);
  emit(sockets.at(-1), 'background_task_update', snapshot);
  await page.waitForTimeout(100);
  assert.match(await page.locator('[data-task-phase]').innerText(), /正在停止/);
  assert.equal(await page.locator('[data-task-action="stop"]').isEnabled(), false);
  emit(sockets.at(-1), 'nsb_csv_complete', { status: 'partial', message: '停止后整理了可用结果', rows: [['192.0.2.1']] });
  emit(sockets.at(-1), 'task_stopped', null);
  emit(sockets.at(-1), 'task_complete', null);
  await page.waitForFunction(() => document.querySelector('[data-task-phase]').textContent.includes('部分完成'));
  assert.match(await page.locator('[data-task-message]').innerText(), /停止后整理/);
  await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 320, height: 950 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true);
  await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });

  emit(sockets.at(-1), 'background_task_missing', null);
  emit(sockets.at(-1), 'scan_progress', { current: 0, total: 20 });
  await page.locator('[data-task-action="background"]').waitFor({ state: 'visible' });
  await page.waitForFunction(() => !document.querySelector('[data-task-action="background"]').disabled);
  await page.locator('[data-task-action="background"]').click();
  await page.locator('[data-task-confirm-ok]').click();
  await page.waitForFunction(() => document.querySelector('[data-task-action="background"]').disabled);
  assert.equal(commands.filter(command => command.type === 'run_in_background').length, 1);
  emit(sockets.at(-1), 'background_task_update', { ...snapshot, resultCount: 6 });
  emit(sockets.at(-1), 'scan_result', { IP: '192.0.2.2' });
  await page.waitForFunction(() => document.querySelector('[data-task-counts]').textContent.includes('扫描结果 6'));
  assert.doesNotMatch(await page.locator('[data-task-counts]').innerText(), /扫描结果 7/);
  emit(sockets.at(-1), 'error', '未发现有效 IP');
  emit(sockets.at(-1), 'task_complete', null);
  await page.waitForFunction(() => document.querySelector('[data-task-phase]').textContent.includes('任务失败'));
  assert.match(await page.locator('[data-task-message]').innerText(), /未发现有效 IP/);
  for (let i = 0; i < 215; i++) emit(sockets.at(-1), 'log', '日志 ' + i);
  await page.waitForFunction(() => document.querySelector('[data-task-log]').textContent.includes('日志 214'));
  assert.equal(await page.locator('[data-task-log] li').count(), 200);
  const oldCount = sockets.length;
  sockets.at(-1).close({ code: 1001, reason: 'test reconnect' });
  await page.waitForFunction(() => document.querySelector('[data-connection]').textContent.includes('重连'));
  await page.waitForTimeout(3400);
  assert.equal(sockets.length, oldCount + 1);
  assert.deepEqual(errors, []);
  await context.close();

  const auth = await browser.newContext();
  let connections = 0;
  await auth.route('**/auth/login', route => route.fulfill({ status: 200, contentType: 'text/html', body: '<h1>Mock login</h1>' }));
  await auth.routeWebSocket('**/ws', ws => { connections++; ws.close({ code: 1008, reason: 'auth expired' }); });
  await auth.route('**/workbench', route => {
    if (route.request().isNavigationRequest()) return route.continue();
    return route.fulfill({ status: 401, body: 'Unauthorized' });
  });
  const authPage = await auth.newPage();
  await authPage.goto(base + '/workbench');
  await authPage.waitForURL('**/auth/login');
  await authPage.waitForTimeout(3200);
  assert.equal(connections, 1);
  await auth.close();
  console.log('PASS: background discovery/poll/follow, confirm/cancel/stop, terminal precedence, safe bounded logs, mobile layout, background action, reconnect, expired authentication.');
} finally { await browser.close(); }
